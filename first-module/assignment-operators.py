# Operadores de Atribuição são operadores utilizados para definir o valor inicial ou sobrescrever o valor de uma variável

# atribuição simples
balance = 500
print(balance) # saída: 500

# atribuição com adição
balance += 200
print(balance) # saída: 700

# atribuição com subtração
balance -= 100
print(balance) # saída: 600

# atribuição com multiplicação
balance *= 2
print(balance) # saída: 1200

# atribuição com divisão
balance /= 4
print(balance) # saída: 300.0

balance = 300

# divisão inteira
balance //= 3
print(balance) # saída: 100

# atribuição com módulo
balance %= 30
print(balance) # saída: 10

# atribuição com exponenciação
balance **= 3
print(balance) # saída: 1000