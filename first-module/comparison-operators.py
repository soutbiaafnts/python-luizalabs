# igualdade
withdraw =  450
balance = 200
print(withdraw == balance)  # False 

# diferença
print(withdraw != balance)  # True

# maior que || maior ou igual a
print(withdraw > balance)  # True
print(withdraw >= balance)  # True

# menor que || menor ou igual a
print(withdraw < balance)  # False
print(withdraw <= balance)  # False
